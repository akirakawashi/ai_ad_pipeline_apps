import { PageHeader } from '../components/common/PageHeader'

const OVERPASS_URL = 'https://overpass-turbo.eu/'

/**
 * Запрос к Overpass API: все крупные дороги в видимой на экране области.
 *
 * `{{bbox}}` — подстановка самого overpass turbo, означает «текущий вид карты».
 * Из-за неё порядок действий там обратный привычному: сначала найти город на
 * карте, только потом выполнять запрос.
 */
const OVERPASS_QUERY = `[out:json][timeout:180];

way
  ["highway"~"motorway|trunk|primary|secondary|tertiary"]
  ({{bbox}});

out geom;`

