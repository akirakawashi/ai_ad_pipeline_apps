/** Шаг инструкции: номер слева, содержимое справа. */
function Step({
  number,
  title,
  children,
}: {
  number: number
  title: string
  children: ReactNode
}) {
  return (
    <li className="panel manual-step">
      <span className="manual-step-number" aria-hidden="true">
        {number}
      </span>
      <div className="manual-step-body">
        <h2>{title}</h2>
        {children}
      </div>
    </li>
  )
}

/** Запрос с кнопкой «Скопировать»: перенабирать его руками никто не должен. */
function CopyableQuery() {
  const [copied, setCopied] = useState(false)

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(OVERPASS_QUERY)
      setCopied(true)
    } catch {
      // Буфер обмена может быть закрыт настройками браузера — тогда запрос
      // просто выделяют мышью, он на экране целиком.
      setCopied(false)
    }
  }

  return (
    <div className="manual-code">
      <pre>{OVERPASS_QUERY}</pre>
      <button className="ghost-button" type="button" onClick={() => void copy()}>
        {copied ? 'Скопировано' : 'Скопировать'}
      </button>
    </div>
  )
}
