import type { CSSProperties } from 'react'

/**
 * Общая тема подсказок для всех графиков.
 *
 * Раньше эти же четыре объекта лежали копиями в `RunCharts`, `RollupCharts` и
 * `RouteShootingsChart` — три одинаковых определения, которые надо было менять
 * втроём. Одиннадцать подсказок на трёх экранах обязаны выглядеть одинаково,
 * поэтому определение одно.
 */

/**
 * Светлая карточка поверх тёмного графика.
 *
 * Тень обязательна: без неё белый прямоугольник на почти чёрном фоне выглядит
 * дырой в странице, а не всплывающей подсказкой.
 */
export const tooltipStyle: CSSProperties = {
  background: '#ffffff',
  border: '1px solid rgba(0, 0, 0, 0.1)',
  borderRadius: 8,
  boxShadow: '0 14px 34px rgba(0, 0, 0, 0.34)',
  color: '#151515',
  padding: '8px 12px',
}

/** Заголовок подсказки — то, на что навели: бренд, съёмка, момент времени. */
export const tooltipLabelStyle: CSSProperties = {
  color: '#151515',
  fontWeight: 600,
}

/**
 * Строки со значениями. Цвет — «чернила», а НЕ цвет серии, хотя по умолчанию
 * Recharts красит их именно им. Причина не в единообразии: на белом фоне серия
 * «Другое» (#b8bec6) стала бы нечитаемой, а «Miranda» (#05c3a1) почти. Какой
 * серии строка, видно по её названию и по самому графику — цвет тут не
 * единственный носитель смысла.
 */
export const tooltipItemStyle: CSSProperties = {
  color: '#3d4148',
}

/** Подсветка столбца под курсором. Она лежит на тёмном графике, не на подсказке. */
export const tooltipCursor = { fill: 'rgba(255, 255, 255, 0.06)' }
